"""網膜 — 「自分が動いたせいで流れる背景」と「対象そのものの動き」を分ける。

【何をする器官か】網膜は光を電気信号に変えるだけの器官ではなく、**その場で計算している**。
そのひとつが object motion sensitivity（OMS）＝
  受容野の**中心と周辺の動きが一致していれば応答を強く抑え、食い違えば応答する**。

  中心と周辺が同じように動く  → 自分（目・頭）が動いたせい → 抑える
  中心だけが動く              → 外の世界で何かが動いた     → 通す

比べているのは「動きの向き」ではなく「動いているかどうか」。中心と周辺が逆向きでも、
速さが揃っていれば抑制される（Ölveczky et al. 2003）。だから**向きを持たない
変化検出（フレーム差分）にもそのまま適用できる**。

═══════════════════════════════════════════════════════════════════
【根拠】
═══════════════════════════════════════════════════════════════════
・Ölveczky BP, Baccus SA, Meister M (2003) "Segregation of object and background
  motion in the retina" Nature 423:401-408 [PMID 12754524]
  ＝サンショウウオ・ウサギの網膜で OMS 神経節細胞を発見。論文の主題そのものが
    「背景の動きと対象の動きを網膜で分ける」。
・Baccus SA, Ölveczky BP, Manu M, Meister M (2008) J Neurosci 28:6807 [PMID 18596156]
  ＝回路の中身。多軸索性アマクリン細胞が**3mm以上**離れた周辺から情報を集め、
    双極細胞の出力を**約0.49倍に割り算する**（除算的抑制）。
・Cell Reports (2025) ＝**マカク網膜の broad thorny 細胞**で同種の性質を確認。
  broad thorny は**上丘への入力の24%**を占める型（Dhande et al. IOVS）。
    つまり上丘は最初から「背景の流れを除いた信号」を受け取っている。
・Inayat S, Barchini J, Chen H, Feng L, Liu X, Cang J (2018) eLife 7:e35261
  ＝**マウス上丘**にも同じ抑制。中心＝半径10度の円、周辺＝半径10〜30度の輪帯で、
    546細胞中455（83.3%）が「周辺が中心と同方向」で抑制された（除算的）。
    この実験は**大脳皮質を切除した状態**で行われた＝皮質に依存しない回路。
      前頭眼野を使う遠心性コピー（新生児では未成熟）と違い、**新生児でも使える**。

═══════════════════════════════════════════════════════════════════
注意：【簡略化・逸脱】
═══════════════════════════════════════════════════════════════════
・新生児（ヒト）で OMS が働いている**直接の証拠は無い**（2026-07-27 の調査で確認）。
  皮質を必要としない回路であること、上丘自体が出生時に機能していることからの推論。
・定量値はサンショウウオ・マウス・サルのもの。**ヒト乳児の値は存在しない**。
・実際の OMS は「中心と周辺の動きの軌道の相関」を見るが、ここでは
  **動きの強さの比較**で近似する[簡略化]。太郎の動き検出は向きを持たないため。
・網膜の細胞ごとの受容野ではなく、画像全体に一様なフィルタとして掛ける[簡略化]。
"""
import numpy as np
from scipy.ndimage import gaussian_filter

# 周辺を見る広さ。マウス上丘は「中心=半径10度／周辺=半径10〜30度の輪帯」
# （Inayat et al. 2018）。輪帯の代表を 20度 とし、ガウスの σ をそこに置く。
SURROUND_DEG = 20.0
# 抑制の強さ。一様に動いているとき、応答が何倍になるか。
# サンショウウオの実測は約 0.49 倍（Baccus et al. 2008）。
UNIFORM_GAIN = 0.49


def object_motion(motion, fovy_deg, surround_deg=SURROUND_DEG,
                  uniform_gain=UNIFORM_GAIN):
    """動きマップから「まわりも一緒に動いている成分」を割り引く。

    out = motion / (1 + k * surround)

    まわりの平均 surround が自分と同じ大きさのとき、応答が uniform_gain 倍に
    なるよう k を決める。k = (1/uniform_gain - 1) / (基準となる動きの大きさ)。
    基準にはそのフレームの動きの代表値（上位側の値）を使い、
    **明るさのスケールに依らない**ようにする。

    Args:
        motion: 動きマップ（2次元、0以上）
        fovy_deg: 画像1辺が視野で何度か（周辺の広さを画素に直すのに使う）
        surround_deg: 周辺を見る広さ[度]
        uniform_gain: 一様に動いているときの残り具合（0〜1）

    Returns:
        抑制後の動きマップ（motion と同じ形）
    """
    a = np.clip(np.asarray(motion, dtype=np.float32), 0, None)
    if a.size == 0 or a.max() <= 1e-12:
        return a
    h, w = a.shape[-2], a.shape[-1]
    # 視野角 → 画素。画像1辺 = fovy_deg なので、1度あたり (画素数/視野角) 画素。
    sigma_px = float(surround_deg) * (max(h, w) / float(fovy_deg))
    # 注意：truncate=2.0（既定は4.0）。σが大きいので既定のままだと計算が重く、
    #   実時間で動かすと制御周期に間に合わない。裾を2σで切っても
    #   「まわりも動いているか」の判定にはほとんど影響しない。
    surround = gaussian_filter(a, sigma_px)

    # 基準の大きさ：そのフレームで実際に動いている場所の代表値。
    # 最大値だと1画素の外れ値に引きずられるので上位の分位点を使う。
    ref = float(np.quantile(a[a > 0], 0.9)) if np.any(a > 0) else 0.0
    if ref <= 1e-12:
        return a
    k = (1.0 / float(uniform_gain) - 1.0) / ref
    return a / (1.0 + k * surround)
