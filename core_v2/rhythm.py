"""1分のリズム（盤面の世界、2026-10-19 下書きから清書）。

脳は世界より速く回る。盤面の世界の1分のあいだに、脳は TICKS_PER_MIN 回進む（世界は1分の間止まっていて、
入口には同じ値が届き続ける）。矢印1本で1回遅れるので、体の内側の入口から「選ぶ」を通って声・体の出口まで
届くのに数回かかる。

1分に1回だけ働く係（覚える・いら立ちを積む・選ぶ）は、その分の入力がちょうど届いた回（位相）で働く。
どの係も脳の reset から自分で回を数えるので、位相はそろっている（体のリズム。生まれつき）。

位相（0 から数える）:
  0 入口（体の内側・目）が世界を受け取る
  1 欲求・体の内側・他の人を読む係へ届く。SEM：意味の辞書が目の前の物をどれくらい知っているかを出す（4段目）
  2 WORTH：ミルクが来たか・誰が来たかが届く → 覚える、見込みを出す、来なかった分を出す
  3 STRESS：来なかった分が届く → いら立ちを積む
  4 気持ちの係へ今のいら立ちが届く
  5 WANT：見込み・不快・この分のいら立ちが届く → 選ぶ
  6 泣く・手を伸ばす係へ届く
  7 声・体の出口から世界へ（世界はこの回の指令で1分進む）
"""

TICKS_PER_MIN = 8
SEM_PHASE = 1
WORTH_PHASE = 2
STRESS_PHASE = 3
WANT_PHASE = 5
OUT_PHASE = 7


def phase(n: int) -> int:
    """reset から n 回目（0 から）が、1分の中の何番目か。"""
    return n % TICKS_PER_MIN
